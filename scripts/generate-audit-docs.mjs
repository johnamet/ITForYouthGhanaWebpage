#!/usr/bin/env node
/**
 * Regenerates the audit documents under docs/audit/ from the analysis scripts.
 *
 * The documents are living: run this after any change to routes, readers,
 * assets or sections rather than hand-editing them, so they never drift from
 * the repository they describe.
 *
 * Usage: node scripts/generate-audit-docs.mjs
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";

const json = (script) =>
  JSON.parse(execFileSync("node", [script, "--json"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));

const routes = json("scripts/discover-routes.mjs");
const coverage = json("scripts/cms-coverage.mjs");
const assets = json("scripts/inventory-assets.mjs");
const pairing = json("scripts/media-pairing.mjs");

mkdirSync("docs/audit", { recursive: true });

const STAMP = `> Generated by \`node scripts/generate-audit-docs.mjs\`. Do not hand-edit; re-run it instead.\n`;

/* ------------------------------------------------- 1. route inventory ------ */

let d = `# Route inventory\n\n${STAMP}\n`;
d += `Routes are discovered from the filesystem, not from the navigation menu, because routes drift out of the nav and orphaned pages are common.\n\n`;
d += `## Totals\n\n`;
d += `| Measure | Count |\n| --- | --- |\n`;
for (const [k, v] of Object.entries(routes.totals)) {
  d += `| ${k.replace(/([A-Z])/g, " $1").toLowerCase()} | ${v} |\n`;
}
d += `\n## Dynamic segments, expanded\n\n`;
d += `A single \`[slug]\` file is not one page. These are the pages it actually produces. Seed-derived counts are a baseline, not a ceiling: Firestore can add more.\n\n`;
d += `| Route | Expands to | Source |\n| --- | --- | --- |\n`;
for (const x of routes.dynamicExpansion) {
  const to = x.expandsTo !== null ? `${x.expandsTo} pages` : x.runtime ? "runtime" : "**unresolved**";
  d += `| \`${x.route}\` | ${to} | ${x.runtime ?? (x.slugs.length ? x.slugs.join(", ") : "—")} |\n`;
}
d += `\n## Chrome\n\nVisible surfaces that also need design attention and are routinely forgotten.\n\n`;
d += `| Kind | File |\n| --- | --- |\n`;
for (const c of routes.chrome) d += `| ${c.kind} | \`${c.file}\` |\n`;

d += `\n## Reconciliation findings\n\n`;
const f = routes.findings;
d += `### Built but unreachable from the navigation or any copy (${f.unreachableFromNavOrCopy.length})\n\n`;
d += f.unreachableFromNavOrCopy.length
  ? f.unreachableFromNavOrCopy.map((r) => `- \`${r}\``).join("\n") + "\n"
  : "_None._\n";
d += `\n### Dead internal links in seed copy (${f.deadInternalLinks.length})\n\n`;
d += f.deadInternalLinks.length
  ? f.deadInternalLinks.map((r) => `- \`${r}\``).join("\n") + "\n"
  : "_None._\n";
d += `\n### Redirects and rewrites (${f.redirects.length})\n\n`;
d += `| From | To |\n| --- | --- |\n`;
for (const r of f.redirects) d += `| \`${r.from}\` | \`${r.to}\` |\n`;

d += `\n## All public routes\n\n`;
for (const r of routes.publicRoutes) d += `- \`${r}\`\n`;
writeFileSync("docs/audit/route-inventory.md", d);

/* ------------------------------------------------- 2. CMS coverage map ----- */

let c = `# CMS coverage map\n\n${STAMP}\n`;
c += `One row per public route, with the sections it renders and the content path behind them.\n\n`;
c += `\`partial\` is the verdict that matters: some fields editable and others hardcoded. That state is invisible from the admin side.\n\n`;
const count = (v) => coverage.rows.filter((r) => r.verdict === v).length;
c += `## Totals\n\n| Measure | Count |\n| --- | --- |\n`;
c += `| public routes | ${coverage.rows.length} |\n`;
c += `| full coverage | ${count("full")} |\n`;
c += `| partial coverage | ${count("partial")} |\n`;
c += `| no coverage | ${count("none")} |\n`;
c += `| readers discovered | ${coverage.readers.length} |\n`;

c += `\n## Coverage by route\n\n`;
c += `| Route | Readers | Collections | Admin editor | Revalidated | Coverage |\n| --- | --- | --- | --- | --- | --- |\n`;
for (const r of coverage.rows) {
  c += `| \`${r.route}\` | ${r.readers.join("<br>") || "_none_"} | ${
    r.collections.join(", ") || "_none_"
  } | ${r.adminEditors.map((a) => `\`${a}\``).join("<br>") || "**missing**"} | ${
    r.revalidated ? "yes" : "**no**"
  } | ${r.verdict === "full" ? "full" : `**${r.verdict}**`} |\n`;
}

c += `\n## Sections rendered per route\n\n`;
for (const r of coverage.rows) {
  c += `### \`${r.route}\`\n\n`;
  c += `Source: \`${r.file}\`\n\n`;
  c += r.sections.length ? r.sections.map((s) => `- ${s}`).join("\n") + "\n\n" : "_No section components._\n\n";
}

c += `## Readers\n\n| Reader | File | Collection | Seed fallback |\n| --- | --- | --- | --- |\n`;
for (const r of coverage.readers.sort((a, b) => a.name.localeCompare(b.name))) {
  const fb = r.operational ? "n/a (submitted data)" : r.hasFallback ? "yes" : "**no**";
  c += `| \`${r.name}\` | \`${r.file}\` | ${r.collection ?? "—"} | ${fb} |\n`;
}
writeFileSync("docs/audit/cms-coverage-map.md", c);

/* ------------------------------------------------- 3. media inventory ----- */

let m = `# Media inventory and pairing gap analysis\n\n${STAMP}\n`;
const t = assets.totals;
m += `## Asset totals\n\n| Measure | Count |\n| --- | --- |\n`;
for (const [k, v] of Object.entries(t)) m += `| ${k.replace(/([A-Z])/g, " $1").toLowerCase()} | ${v} |\n`;

m += `\n## Orientation by directory\n\n`;
m += `Orientation matters more than it sounds: a layout needing tall portrait media cannot be built from a library of wide landscape shots.\n\n`;
m += `| Directory | Files | Landscape | Portrait | Square | Unused | Over 1 MB |\n| --- | --- | --- | --- | --- | --- | --- |\n`;
for (const [dir, v] of Object.entries(assets.byDirectory).sort()) {
  m += `| \`${dir}\` | ${v.count} | ${v.landscape} | ${v.portrait} | ${v.square} | ${v.unused} | ${v.oversized} |\n`;
}

m += `\n## Needs optimisation (over 1 MB)\n\n| Size | Dimensions | Path |\n| --- | --- | --- |\n`;
for (const a of assets.oversized) m += `| ${a.kb} KB | ${a.width}×${a.height} | \`${a.path}\` |\n`;

m += `\n## Generic filenames\n\nUnmaintainable at scale; rename with care because other code may reference them.\n\n`;
for (const p of assets.genericNames) m += `- \`${p}\`\n`;

if (assets.extensionMismatch?.length) {
  m += `\n## Extension does not match content\n\n`;
  for (const a of assets.extensionMismatch) m += `- \`${a.path}\` is really ${a.actually}\n`;
}

m += `\n## Reused across more than one source file\n\n`;
m += `Unintentional repetition is invisible when reviewing one page at a time and obvious to a visitor browsing the site.\n\n`;
m += `| Uses | Path |\n| --- | --- |\n`;
for (const a of assets.reused) m += `| ${a.refCount} | \`${a.path}\` |\n`;

m += `\n## Never referenced in source (${assets.unreferenced.length})\n\n`;
for (const p of assets.unreferenced) m += `- \`${p}\`\n`;

const pt = pairing.totals;
m += `\n## Pairing gap analysis\n\n| Measure | Count |\n| --- | --- |\n`;
m += `| public routes | ${pt.routes} |\n| components scanned | ${pt.componentsScanned} |\n`;
m += `| content sections | ${pt.contentSections} |\n| paired with media or a graphic form | ${pt.paired} |\n`;
m += `| unpaired text-only | ${pt.textOnly} |\n| routes fully paired | ${pt.routesFullyPaired} of ${pt.routes} |\n`;

m += `\nStructural components (section openers, link grids, forms) and purposeful graphic forms (a sequence drawn as a line, a tree over real groupings, figures from real numbers) are excluded from the gap list, per the addendum.\n`;

m += `\n### Unpaired content sections\n\n| Route | Section | Suggested resolution |\n| --- | --- | --- |\n`;
for (const r of pairing.rows.filter((x) => x.textOnly.length)) {
  for (const s of r.textOnly) {
    m += `| \`${r.route}\` | ${s} | _decide: photograph, video, graphic form, or merge into neighbour_ |\n`;
  }
}
writeFileSync("docs/audit/media-inventory.md", m);

console.log("wrote:");
for (const f of ["route-inventory.md", "cms-coverage-map.md", "media-inventory.md"]) {
  console.log(`  docs/audit/${f}`);
}
