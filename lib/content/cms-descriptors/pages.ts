/**
 * Page-copy editors for the areas outside the Laptop Bank.
 *
 * Same pattern as lib/content/laptop-bank-page-seeds.ts: the seed stays in code
 * and remains the fallback, the editor's fields are generated by walking it,
 * and stored overrides are merged back on read.
 *
 * WHY GENERATE RATHER THAN KEEP THE HAND-WRITTEN FORMS
 * A hand-written form can only edit the fields somebody remembered to add. A
 * string added to a content object in code is silently uneditable until a
 * developer notices — which is the state every page form in this repo was in.
 * The contact page alone generates 83 editable fields from a 356-line form.
 */

export type PageSeedEntry = {
  /**
   * The admin route key, after the `page-` prefix.
   *
   * Distinct from `docId` because the two namespaces are different: the impact
   * testimonials PAGE and the testimonial RECORDS are separate editors, and
   * `page-testimonials` next to `testimonial` would be a trap for whoever
   * reads the sidebar next.
   */
  key: string;
  /** Firestore document id. */
  docId: string;
  hub: string;
  label: string;
  /** The public route this copy renders on. */
  route: string;
  collection: string;
  description: string;
  /** Paths to rebuild after a write. */
  revalidatePaths: string[];
  seed: Record<string, unknown>;
};

